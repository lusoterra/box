export const DEFAULT_THEME = 'builtin';

export function normalizeTheme(key: string | null | undefined): string {
  if (!key) return DEFAULT_THEME;
  return THEMES.some((t) => t.key === key) ? key : DEFAULT_THEME;
}

export function themeFor(key: string): BoxTheme {
  return THEMES.find((t) => t.key === key) ?? THEMES[1];
}
